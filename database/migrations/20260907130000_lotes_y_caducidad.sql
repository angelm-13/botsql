-- Lotes y caducidad: lo que le pone fecha a una parte del saldo.
--
-- Que faltaba
-- -----------
-- Un saldo de 300 sacos no dice cuando caduca ninguno. Con eso, lo que se vence
-- se descubre en el anaquel, y quien lo descubre ya no puede hacer nada: ni
-- devolverlo al proveedor, ni sacarlo antes, ni dejar de comprar tanto.
--
-- El lote le pone fecha a una parte del saldo:
--
--     300 sacos = lote L-441 (120, vence 2027-03-01)
--               + lote L-508 (180, vence 2027-09-15)
--
-- Y con eso la salida puede servirse del que vence antes, que es el unico orden
-- que reduce la merma por caducidad.
--
-- Tres tablas, y por que cada una
-- -------------------------------
-- `inventory_lot`: el lote. Producto, codigo del proveedor y fecha. Sin
-- cantidades, porque un lote se reparte entre ubicaciones.
--
-- `inventory_lot_balance`: cuanto queda de ese lote en cada sitio. Se podria
-- derivar sumando el libro, y se guarda por lo mismo que `inventory_stock`: sin
-- saldo guardado, cada consulta de "que hay" recorre el libro entero.
--
-- `nm_inventory_ledger_lot`: de que lotes salio cada movimiento. Hace falta
-- porque una salida de 30 puede cubrirse con tres lotes y el libro escribe UN
-- renglon por movimiento: sin el desglose, el renglon diria que salieron 30 sin
-- decir de donde, y el rastro se corta justo donde el proveedor pregunta.
--
-- El interruptor
-- --------------
-- `product.lot_control`, apagado por omision. Encenderlo obliga a nombrar el
-- lote en cada entrada de ese producto, y eso solo vale la pena en lo que
-- caduca; en lo demas seria un campo mas que llenar sin nada que contestar a
-- cambio. Al nacer apagado, nada de lo que ya existe cambia de comportamiento.
--
-- No se enciende en lo serializado: un producto rastreado pieza por pieza ya
-- tiene una fila por unidad en `inventory_asset`, y ponerle lotes encima seria
-- llevar la misma cosa por dos caminos. Lo impide un CHECK.
--
-- Que NO lleva
-- ------------
-- Costo. Se dejo fuera a proposito: valuar el almacen es otra cosa -pide costo
-- promedio o FIFO, y decidir cual- y meterla aqui a medias daria una cifra que
-- parece un costo sin serlo.

BEGIN;

-- 1. El interruptor por producto.
ALTER TABLE product
    ADD COLUMN IF NOT EXISTS lot_control BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
    ALTER TABLE product
        ADD CONSTRAINT ck_product_lot_control_solo_fungible
        CHECK (NOT (lot_control AND tracking_mode = 'serializado'));
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

-- 2. El lote.
CREATE TABLE IF NOT EXISTS inventory_lot (
    id_inventory_lot INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_product INTEGER NOT NULL
        REFERENCES product(id_product) DEFERRABLE INITIALLY IMMEDIATE,
    lot_code VARCHAR(60) NOT NULL,
    expiry_date DATE,
    received_on DATE,
    note VARCHAR(250),
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inventory_lot_product
    ON inventory_lot (id_product);

-- Por donde entra "que vence pronto": la consulta ordena por fecha.
CREATE INDEX IF NOT EXISTS idx_inventory_lot_expiry
    ON inventory_lot (expiry_date)
    WHERE expiry_date IS NOT NULL AND deletion_date IS NULL;

-- Dos lotes L-441 del mismo producto son el mismo lote capturado dos veces, y
-- con los dos vivos la mitad de las salidas descontaria de uno y la mitad del
-- otro.
CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_lot_product_code
    ON inventory_lot (id_product, lower(lot_code))
    WHERE deletion_date IS NULL;

-- 3. Cuanto queda de cada lote en cada sitio.
CREATE TABLE IF NOT EXISTS inventory_lot_balance (
    id_inventory_lot_balance INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inventory_lot INTEGER NOT NULL
        REFERENCES inventory_lot(id_inventory_lot) DEFERRABLE INITIALLY IMMEDIATE,
    id_location INTEGER NOT NULL
        REFERENCES location(id_location) DEFERRABLE INITIALLY IMMEDIATE,
    quantity INTEGER NOT NULL DEFAULT 0,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Un saldo de lote negativo no existe: significaria que salio de un lote mas
    -- de lo que ese lote traia.
    CONSTRAINT ck_inventory_lot_balance_no_negativo CHECK (quantity >= 0)
);

CREATE INDEX IF NOT EXISTS idx_inventory_lot_balance_lot
    ON inventory_lot_balance (id_inventory_lot);
CREATE INDEX IF NOT EXISTS idx_inventory_lot_balance_location
    ON inventory_lot_balance (id_location);

-- Un lote tiene UN saldo por ubicacion. Dos filas se sumarian a mano en unos
-- sitios del codigo y en otros no.
CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_lot_balance_lot_location
    ON inventory_lot_balance (id_inventory_lot, id_location);

-- 4. De que lotes fue cada movimiento del libro.
CREATE TABLE IF NOT EXISTS nm_inventory_ledger_lot (
    id_nm_inventory_ledger_lot INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inventory_ledger INTEGER NOT NULL
        REFERENCES inventory_ledger(id_inventory_ledger) DEFERRABLE INITIALLY IMMEDIATE,
    id_inventory_lot INTEGER NOT NULL
        REFERENCES inventory_lot(id_inventory_lot) DEFERRABLE INITIALLY IMMEDIATE,
    -- Con el mismo signo que el movimiento: negativo si salio.
    quantity_delta INTEGER NOT NULL,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_nm_inventory_ledger_lot_no_cero CHECK (quantity_delta <> 0)
);

CREATE INDEX IF NOT EXISTS idx_nm_inventory_ledger_lot_ledger
    ON nm_inventory_ledger_lot (id_inventory_ledger);
CREATE INDEX IF NOT EXISTS idx_nm_inventory_ledger_lot_lot
    ON nm_inventory_ledger_lot (id_inventory_lot);

COMMIT;

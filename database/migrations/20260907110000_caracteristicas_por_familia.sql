-- Las caracteristicas del material: la familia las declara, el material las llena.
--
-- Que faltaba
-- -----------
-- Con familia, tipo y marca se llega hasta "desarmador Truper plano". El resto
-- -el largo, el material del mango, el calibre, los litros- se escribia dentro
-- de la descripcion:
--
--     "Desarmador plano 6 pulgadas mango de goma"
--
-- Eso se puede leer y no se puede usar: no se puede agrupar, ni filtrar, ni
-- contestar "cuantos de 6 pulgadas tengo".
--
-- Por que no columnas
-- -------------------
-- Porque cada familia pide otras. Un desarmador tiene largo y mango; un cable
-- calibre y metros; la pintura litros y acabado. Con columnas fijas la tabla
-- acaba con veinte, dieciocho vacias en cada renglon, y aun asi falta la de la
-- familia que entre manana.
--
-- Por que no una columna JSON
-- ---------------------------
-- Porque nadie declararia que campos aplican, asi que cada quien escribiria la
-- llave como quisiera -"largo", "longitud", "tamano"- y filtrar dejaria de ser
-- fiable. Es el mismo problema que tenia `product_status` cuando era un
-- VARCHAR libre donde cada quien ponia "Nuevo", "nuevo", "NUEVO" o "n".
--
-- Como queda
-- ----------
-- Tres tablas, y es el mismo patron que ya sigue el tipo de material:
--
--   * `material_attribute`: la FAMILIA declara sus caracteristicas. Asi el alta
--     de un material solo ofrece las de su familia, y no se puede capturar
--     "litros" en un desarmador;
--   * `material_attribute_option`: los valores permitidos cuando la
--     caracteristica es una lista. Sin esto, "acabado: mate" acaba compitiendo
--     con "Mate" y "MATE", y agrupar por acabado devuelve tres grupos donde hay
--     uno;
--   * `nm_material_attribute`: el valor que da cada material.
--
-- Las tres formas de un valor
-- ---------------------------
-- `data_type` dice cual columna de valor se llena:
--
--     texto  -> value_text
--     numero -> value_text y value_number
--     lista  -> value_text e id_material_attribute_option
--
-- El numero va aparte a proposito: comparado como texto, "10" queda por debajo
-- de "6", asi que "de 6 pulgadas o mas" daria la respuesta equivocada. Y
-- `value_text` se llena SIEMPRE en los tres casos, porque es el valor como se
-- muestra: pintar la lista de caracteristicas de un material no deberia
-- depender de resolver antes de que tipo era cada una.

BEGIN;

-- 1. La caracteristica que declara la familia.
CREATE TABLE IF NOT EXISTS material_attribute (
    id_material_attribute INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_product_family INTEGER NOT NULL
        REFERENCES product_family(id_product_family) DEFERRABLE INITIALLY IMMEDIATE,
    attribute_name VARCHAR(80) NOT NULL,
    data_type VARCHAR(20) NOT NULL,
    unit_label VARCHAR(20),
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT ck_material_attribute_data_type
        CHECK (data_type IN ('texto', 'numero', 'lista'))
);

CREATE INDEX IF NOT EXISTS idx_material_attribute_family
    ON material_attribute (id_product_family);

-- Dos "largo" en desarmadores son el mismo campo capturado dos veces, y con los
-- dos vivos la mitad de los materiales llena uno y la mitad el otro.
CREATE UNIQUE INDEX IF NOT EXISTS uq_material_attribute_family_name
    ON material_attribute (id_product_family, attribute_name)
    WHERE deletion_date IS NULL;

-- 2. Los valores permitidos, cuando la caracteristica es una lista.
CREATE TABLE IF NOT EXISTS material_attribute_option (
    id_material_attribute_option INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_material_attribute INTEGER NOT NULL
        REFERENCES material_attribute(id_material_attribute) DEFERRABLE INITIALLY IMMEDIATE,
    option_value VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_material_attribute_option_attribute
    ON material_attribute_option (id_material_attribute);

CREATE UNIQUE INDEX IF NOT EXISTS uq_material_attribute_option_value
    ON material_attribute_option (id_material_attribute, option_value)
    WHERE deletion_date IS NULL;

-- 3. El valor que da cada material.
CREATE TABLE IF NOT EXISTS nm_material_attribute (
    id_nm_material_attribute INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_material INTEGER NOT NULL
        REFERENCES material(id_material) DEFERRABLE INITIALLY IMMEDIATE,
    id_material_attribute INTEGER NOT NULL
        REFERENCES material_attribute(id_material_attribute) DEFERRABLE INITIALLY IMMEDIATE,
    value_text VARCHAR(200),
    value_number NUMERIC(14,4),
    id_material_attribute_option INTEGER
        REFERENCES material_attribute_option(id_material_attribute_option)
        DEFERRABLE INITIALLY IMMEDIATE,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    -- Un valor vacio en las tres columnas no es un valor: es una fila que dice
    -- que la caracteristica se capturo sin capturarla.
    CONSTRAINT ck_nm_material_attribute_tiene_valor
        CHECK (value_text IS NOT NULL
               OR value_number IS NOT NULL
               OR id_material_attribute_option IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_nm_material_attribute_material
    ON nm_material_attribute (id_material);
CREATE INDEX IF NOT EXISTS idx_nm_material_attribute_attribute
    ON nm_material_attribute (id_material_attribute);

-- Un material tiene a lo mas UN valor por caracteristica. Dos filas de "largo"
-- para el mismo desarmador son el mismo dato dos veces, y con las dos vivas no
-- hay forma de saber cual vale.
CREATE UNIQUE INDEX IF NOT EXISTS uq_nm_material_attribute_material_attribute
    ON nm_material_attribute (id_material, id_material_attribute)
    WHERE deletion_date IS NULL;

-- Para "cuantos desarmadores de 6 pulgadas hay": la busqueda entra por la
-- caracteristica y compara el numero, no el texto.
CREATE INDEX IF NOT EXISTS idx_nm_material_attribute_numero
    ON nm_material_attribute (id_material_attribute, value_number)
    WHERE value_number IS NOT NULL AND deletion_date IS NULL;

COMMIT;

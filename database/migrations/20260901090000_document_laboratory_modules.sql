BEGIN;

CREATE TABLE IF NOT EXISTS document_category (
    id_document_category INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document (
    id_document INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyect INTEGER NOT NULL REFERENCES proyect(id_proyect) DEFERRABLE INITIALLY IMMEDIATE,
    id_document_category INTEGER NOT NULL REFERENCES document_category(id_document_category) DEFERRABLE INITIALLY IMMEDIATE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    business_reference_type VARCHAR(80),
    business_reference_value VARCHAR(150),
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    issue_date DATE,
    expiration_date DATE,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT ck_document_status CHECK (status IN ('draft', 'issued', 'signed', 'rejected', 'cancelled')),
    CONSTRAINT ck_document_dates CHECK (expiration_date IS NULL OR issue_date IS NULL OR expiration_date >= issue_date)
);

CREATE TABLE IF NOT EXISTS laboratory_equipment (
    id_laboratory_equipment INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyect INTEGER NOT NULL REFERENCES proyect(id_proyect) DEFERRABLE INITIALLY IMMEDIATE,
    id_customer_supplier INTEGER NOT NULL REFERENCES customer_supplier(id_customer_supplier) DEFERRABLE INITIALLY IMMEDIATE,
    equipment_type VARCHAR(100) NOT NULL,
    brand VARCHAR(100),
    model VARCHAR(100),
    serial_number VARCHAR(120),
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT uq_laboratory_equipment_owner_serial UNIQUE (id_proyect, id_customer_supplier, serial_number)
);

CREATE TABLE IF NOT EXISTS laboratory_service_order (
    id_laboratory_service_order INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyect INTEGER NOT NULL REFERENCES proyect(id_proyect) DEFERRABLE INITIALLY IMMEDIATE,
    folio VARCHAR(80) NOT NULL,
    id_laboratory_equipment INTEGER NOT NULL REFERENCES laboratory_equipment(id_laboratory_equipment) DEFERRABLE INITIALLY IMMEDIATE,
    id_customer_supplier INTEGER NOT NULL REFERENCES customer_supplier(id_customer_supplier) DEFERRABLE INITIALLY IMMEDIATE,
    id_logistics_contact INTEGER REFERENCES logistics_contact(id_logistics_contact) DEFERRABLE INITIALLY IMMEDIATE,
    contact_name VARCHAR(150) NOT NULL,
    contact_email VARCHAR(100),
    contact_phone VARCHAR(30),
    delivered_accessories TEXT,
    reception_condition TEXT,
    reported_failure TEXT NOT NULL,
    technical_diagnosis TEXT,
    recommended_repair TEXT,
    work_performed TEXT,
    id_technician INTEGER REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    priority VARCHAR(20) NOT NULL DEFAULT 'normal',
    estimated_budget NUMERIC(14, 2),
    final_cost NUMERIC(14, 2),
    estimated_repair_time VARCHAR(100),
    reception_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diagnosis_date TIMESTAMP,
    estimated_delivery_date TIMESTAMP,
    actual_delivery_date TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'received',
    observations TEXT,
    service_conditions TEXT,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT uq_laboratory_service_order_project_folio UNIQUE (id_proyect, folio),
    CONSTRAINT ck_laboratory_service_order_priority CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
    CONSTRAINT ck_laboratory_service_order_costs CHECK (
        (estimated_budget IS NULL OR estimated_budget >= 0) AND (final_cost IS NULL OR final_cost >= 0)
    ),
    CONSTRAINT ck_laboratory_service_order_status CHECK (status IN (
        'received', 'awaiting_diagnosis', 'diagnosing', 'pending_authorization',
        'authorized', 'not_authorized', 'repairing', 'awaiting_parts', 'repaired',
        'not_repairable', 'ready_for_delivery', 'delivered', 'cancelled'
    ))
);

CREATE TABLE IF NOT EXISTS laboratory_service_order_status_history (
    id_laboratory_service_order_status_history INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_laboratory_service_order INTEGER NOT NULL REFERENCES laboratory_service_order(id_laboratory_service_order) DEFERRABLE INITIALLY IMMEDIATE,
    previous_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    comments TEXT,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document_version (
    id_document_version INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_document INTEGER NOT NULL REFERENCES document(id_document) DEFERRABLE INITIALLY IMMEDIATE,
    version INTEGER NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    extension VARCHAR(10) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'uploaded',
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    source_snapshot JSONB,
    id_parent_document_version INTEGER REFERENCES document_version(id_document_version) DEFERRABLE INITIALLY IMMEDIATE,
    generated_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    generation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT uq_document_version_number UNIQUE (id_document, version),
    CONSTRAINT ck_document_version_number CHECK (version > 0),
    CONSTRAINT ck_document_version_size CHECK (file_size > 0),
    CONSTRAINT ck_document_version_source CHECK (source IN ('uploaded', 'generated', 'signed_scan')),
    CONSTRAINT ck_document_version_status CHECK (status IN ('draft', 'issued', 'signed', 'rejected', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS document_relation (
    id_document_relation INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_document INTEGER NOT NULL REFERENCES document(id_document) DEFERRABLE INITIALLY IMMEDIATE,
    relation_type VARCHAR(40) NOT NULL,
    id_customer_supplier INTEGER REFERENCES customer_supplier(id_customer_supplier) DEFERRABLE INITIALLY IMMEDIATE,
    id_employee INTEGER REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    id_laboratory_equipment INTEGER REFERENCES laboratory_equipment(id_laboratory_equipment) DEFERRABLE INITIALLY IMMEDIATE,
    id_laboratory_service_order INTEGER REFERENCES laboratory_service_order(id_laboratory_service_order) DEFERRABLE INITIALLY IMMEDIATE,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP,
    CONSTRAINT ck_document_relation_single_target CHECK (
        num_nonnulls(id_customer_supplier, id_employee, id_laboratory_equipment, id_laboratory_service_order) = 1
    )
);

CREATE INDEX IF NOT EXISTS ix_document_project ON document(id_proyect) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_category ON document(id_document_category) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_version_document ON document_version(id_document) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_version_sha256 ON document_version(sha256);
CREATE INDEX IF NOT EXISTS ix_document_relation_document ON document_relation(id_document) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_relation_customer ON document_relation(id_customer_supplier) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_relation_employee ON document_relation(id_employee) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_relation_equipment ON document_relation(id_laboratory_equipment) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_document_relation_order ON document_relation(id_laboratory_service_order) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_equipment_project ON laboratory_equipment(id_proyect) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_equipment_customer ON laboratory_equipment(id_customer_supplier) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_service_order_project ON laboratory_service_order(id_proyect) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_service_order_customer ON laboratory_service_order(id_customer_supplier) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_service_order_technician ON laboratory_service_order(id_technician) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_service_order_status ON laboratory_service_order(status) WHERE deletion_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_laboratory_service_order_history_order ON laboratory_service_order_status_history(id_laboratory_service_order, creation_date);

INSERT INTO document_category (code, name, description, created_by)
SELECT category.code, category.name, category.description, COALESCE((SELECT MIN(id_user) FROM "user"), 1)
FROM (VALUES
    ('employee', 'Empleado', 'Documentos relacionados con empleados'),
    ('customer', 'Cliente', 'Documentos relacionados con clientes'),
    ('supplier', 'Proveedor', 'Documentos relacionados con proveedores'),
    ('certification', 'Certificacion', 'Certificaciones y constancias'),
    ('receipt', 'Recibo', 'Recibos y comprobantes'),
    ('internal_process', 'Proceso interno', 'Documentacion de procesos internos'),
    ('equipment_reception', 'Recepcion de equipo', 'Evidencias de recepcion del equipo'),
    ('diagnostic_report', 'Reporte de diagnostico', 'Ordenes de servicio y reportes de diagnostico'),
    ('signed_diagnostic_report', 'Reporte de diagnostico firmado', 'Copias firmadas o escaneadas')
) AS category(code, name, description)
WHERE EXISTS (SELECT 1 FROM "user")
ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description, active = TRUE;

INSERT INTO field (table_name, field_name, created_by, creation_date, last_update_date)
SELECT entity.table_name, column_name, COALESCE((SELECT MIN(id_user) FROM "user"), 1), CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM (VALUES
    ('document'), ('document_category'), ('document_version'), ('document_relation'),
    ('laboratory_equipment'), ('laboratory_service_order'), ('laboratory_service_order_status_history')
) AS entity(table_name)
CROSS JOIN LATERAL (
    SELECT columns.column_name
    FROM information_schema.columns AS columns
    WHERE columns.table_schema = current_schema() AND columns.table_name = entity.table_name
) AS columns
WHERE EXISTS (SELECT 1 FROM "user")
  AND NOT EXISTS (
      SELECT 1 FROM field current_field
      WHERE current_field.table_name = entity.table_name AND current_field.field_name = columns.column_name
  );

INSERT INTO entity_permission (
    id_permission, entity_name, control_type, menu_location, menu_group,
    menu_group_icon, menu_label, menu_order, created_by, creation_date, last_update_date
)
SELECT permission.id_permission, entity.entity_name,
       CASE
           WHEN LOWER(permission.permission_description) LIKE '%admin%' THEN 15
           WHEN entity.entity_name IN ('document', 'document_version', 'document_relation', 'laboratory_equipment', 'laboratory_service_order') THEN 7
           ELSE 2
       END,
       CASE WHEN entity.entity_name IN ('document', 'laboratory_equipment', 'laboratory_service_order') THEN 'sidebar' ELSE 'hidden' END,
       'Laboratorio', 'flask-conical', entity.menu_label, entity.menu_order,
       COALESCE((SELECT MIN(id_user) FROM "user"), 1), CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM permission
CROSS JOIN (VALUES
    ('document', 'Documentos', 610),
    ('document_category', 'Categorias documentales', 611),
    ('document_version', 'Versiones documentales', 612),
    ('document_relation', 'Relaciones documentales', 613),
    ('laboratory_equipment', 'Equipos de laboratorio', 620),
    ('laboratory_service_order', 'Ordenes de servicio', 621),
    ('laboratory_service_order_status_history', 'Historial de ordenes', 622)
) AS entity(entity_name, menu_label, menu_order)
WHERE EXISTS (SELECT 1 FROM "user")
  AND NOT EXISTS (
      SELECT 1 FROM entity_permission current_permission
      WHERE current_permission.id_permission = permission.id_permission
        AND current_permission.entity_name = entity.entity_name
        AND current_permission.deletion_date IS NULL
  );

COMMIT;
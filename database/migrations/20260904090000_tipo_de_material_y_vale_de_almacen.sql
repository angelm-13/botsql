-- El almacen, normalizado: el tipo del material y el vale como rastro.
--
-- El modelo que hay que sostener
-- ------------------------------
-- Un material se define por tres cosas: su FAMILIA, su TIPO y su MARCA.
--
--     familia "Desarmadores" + tipo "Plano" + marca "Truper"
--     familia "Desarmadores" + tipo "De cruz" + marca "Lion Tools"
--
-- De las tres, `material` ya tenia familia y marca. El tipo no existia, asi que
-- la distincion entre un desarmador plano y uno de cruz vivia dentro del texto
-- de la descripcion: se podia escribir, pero no agrupar, ni filtrar, ni contar.
--
-- El tipo cuelga de la FAMILIA y no suelto
-- ----------------------------------------
-- "Plano" no significa nada por si mismo: es un tipo de desarmador. Con una
-- tabla plana de tipos, el alta de un material dejaria elegir "cemento" de tipo
-- "de cruz" y nada lo impediria. Con el tipo colgando de la familia, el
-- desplegable solo ofrece los tipos de la familia elegida, y el par
-- (familia, tipo) es unico.
--
-- El estatus del producto pasa a ser catalogo
-- -------------------------------------------
-- `product.product_status` era un VARCHAR(20) libre: cada quien escribia
-- "Nuevo", "nuevo", "NUEVO" o "n". No se puede filtrar por algo que no tiene
-- valores acotados.
--
-- No se crea una tabla nueva porque ya existe: `inventory_status` es un
-- catalogo de estados con `entity_scope`, hecho justo para esto. El producto
-- apunta ahi, con los estados sembrados en el alcance `product`. La columna de
-- texto se conserva y no se borra: es el dato historico de lo ya capturado, y
-- tirarlo para ganar limpieza seria perder informacion que nadie pidio perder.
--
-- El vale, y por que no hacia falta inventarlo
-- --------------------------------------------
-- Un vale es un `incident`: tiene tipo -prestamo, salida, devolucion- via
-- `incident_type`, tiene responsable via `id_user`, tiene estado y tiene fechas.
-- Eso ya estaba entero.
--
-- Y sus renglones son `nm_incident_product`, que ya unia el vale con el
-- producto y la cantidad. Le faltaban tres cosas para servir de rastro:
--
--   * **donde**. Un vale de prestamo mueve algo de un sitio a otro; sin la
--     ubicacion, el vale dice que salio pero no de donde ni a donde;
--   * **que pieza**. Con herramienta rastreada una por una, "un desarmador del
--     producto 12" no basta: hay que saber cual, y eso es `inventory_asset`;
--   * **cuando empieza y cuando vence**. Habia `close_date` -cuando se cerro-
--     pero no cuando debia volver, asi que no se podia listar lo vencido.
--
-- Las dos formas de rastrear conviven a proposito
-- -----------------------------------------------
-- Un renglon del vale apunta a `id_product` SIEMPRE, y a
-- `id_inventory_asset` solo cuando el material se rastrea pieza por pieza. Es
-- lo que ya decide `product.tracking_mode`:
--
--   * herramienta de uso interno -> `serializado`: el vale nombra la pieza,
--     porque devolver "un desarmador" no cierra el prestamo del desarmador que
--     se llevaron;
--   * mercancia de compra-venta -> `fungible`: el vale nombra cantidad, porque
--     nadie etiqueta trescientos tornillos uno por uno.
--
-- Un CHECK impide la combinacion sin sentido: si hay pieza, la cantidad es 1.

BEGIN;

-- 1. El tipo de material, dentro de su familia.
CREATE TABLE IF NOT EXISTS material_type (
    id_material_type INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_product_family INTEGER NOT NULL
        REFERENCES product_family(id_product_family) DEFERRABLE INITIALLY IMMEDIATE,
    material_type_description VARCHAR(120) NOT NULL,
    created_by INTEGER NOT NULL REFERENCES "user"(id_user) DEFERRABLE INITIALLY IMMEDIATE,
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_update_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deletion_date TIMESTAMP
);

-- El par (familia, tipo) es unico. Dos "Plano" en desarmadores son el mismo
-- tipo capturado dos veces, y con los dos vivos la mitad de los materiales
-- apunta a uno y la mitad al otro.
CREATE UNIQUE INDEX IF NOT EXISTS uq_material_type_family_description
    ON material_type (id_product_family, material_type_description)
    WHERE deletion_date IS NULL;

ALTER TABLE material
    ADD COLUMN IF NOT EXISTS id_material_type INTEGER
        REFERENCES material_type(id_material_type) DEFERRABLE INITIALLY IMMEDIATE;

-- Nullable a proposito: los materiales que ya existen no tienen tipo y no se
-- les puede inventar uno. Se captura cuando alguien los edite.
CREATE INDEX IF NOT EXISTS idx_material_id_material_type
    ON material (id_material_type);

-- 2. El estatus del producto, contra el catalogo que ya existe.
ALTER TABLE product
    ADD COLUMN IF NOT EXISTS id_inventory_status INTEGER
        REFERENCES inventory_status(id_inventory_status) DEFERRABLE INITIALLY IMMEDIATE;

CREATE INDEX IF NOT EXISTS idx_product_id_inventory_status
    ON product (id_inventory_status);

-- Los estados con los que se nace. `entity_scope = 'product'` es lo que hace
-- que el desplegable del producto no ofrezca los estados de una incidencia.
--
-- El departamento y el nivel se RESUELVEN de lo que exista, no se escriben.
-- `inventory_status.id_department` es NOT NULL con DEFAULT 4 y
-- `id_minimum_level` con DEFAULT 2, y en una base donde esos identificadores no
-- existen -la de desarrollo tiene un solo departamento, el 1- el INSERT falla
-- en el COMMIT contra la llave ajena. Medido al aplicar esta migracion la
-- primera vez.
--
-- Y si no hay departamento o nivel ninguno, no se siembra: dejar la migracion
-- reventar por eso pararia el despliegue entero por un catalogo opcional.
INSERT INTO inventory_status (
    inventory_status_code, inventory_status_description, color,
    entity_scope, is_active, is_terminal, sort_order,
    id_department, id_subdepartment, id_minimum_level, created_by
)
SELECT v.codigo, v.descripcion, v.color, 'product', TRUE, v.terminal, v.orden,
       (SELECT MIN(id_department) FROM department WHERE deletion_date IS NULL),
       NULL,
       (SELECT MIN(id_level) FROM level WHERE deletion_date IS NULL),
       1
FROM (VALUES
    ('nuevo',      'Nuevo',           '#15803d', FALSE, 10),
    ('usado',      'Usado',           '#1b7a60', FALSE, 20),
    ('en_reparacion', 'En reparacion', '#b45309', FALSE, 30),
    ('danado',     'Danado',          '#9f1239', FALSE, 40),
    ('retirado',   'Retirado',        '#64748b', TRUE,  50)
) AS v (codigo, descripcion, color, terminal, orden)
WHERE EXISTS (SELECT 1 FROM department WHERE deletion_date IS NULL)
  AND EXISTS (SELECT 1 FROM level WHERE deletion_date IS NULL)
  AND NOT EXISTS (
    SELECT 1 FROM inventory_status s
    WHERE s.inventory_status_code = v.codigo
      AND s.entity_scope = 'product'
);

-- 3. El renglon del vale: donde, que pieza, desde cuando y hasta cuando.
ALTER TABLE nm_incident_product
    ADD COLUMN IF NOT EXISTS id_inventory_asset INTEGER
        REFERENCES inventory_asset(id_inventory_asset) DEFERRABLE INITIALLY IMMEDIATE,
    -- De donde sale.
    ADD COLUMN IF NOT EXISTS id_location_from INTEGER
        REFERENCES location(id_location) DEFERRABLE INITIALLY IMMEDIATE,
    -- Donde queda alojado. Puede ser otra ubicacion del almacen o ninguna, si
    -- se entrega a una persona y no a un sitio.
    ADD COLUMN IF NOT EXISTS id_location_to INTEGER
        REFERENCES location(id_location) DEFERRABLE INITIALLY IMMEDIATE,
    -- Que le pasa a la existencia. Es el dato que el libro de inventario
    -- necesita para saber si descontar, devolver o solo cambiar de sitio.
    ADD COLUMN IF NOT EXISTS direction VARCHAR(20),
    ADD COLUMN IF NOT EXISTS start_date TIMESTAMP,
    -- Cuando debe volver. Sin esto no se puede listar lo vencido, que es la
    -- razon de llevar vales.
    ADD COLUMN IF NOT EXISTS due_date TIMESTAMP;

CREATE INDEX IF NOT EXISTS idx_nm_incident_product_asset
    ON nm_incident_product (id_inventory_asset);
CREATE INDEX IF NOT EXISTS idx_nm_incident_product_abiertos
    ON nm_incident_product (due_date)
    WHERE close_date IS NULL AND deletion_date IS NULL;

DO $$
BEGIN
    ALTER TABLE nm_incident_product
        ADD CONSTRAINT ck_nm_incident_product_direction
        CHECK (direction IS NULL OR direction IN ('salida', 'entrada', 'traslado'));
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

DO $$
BEGIN
    -- Una pieza es una pieza: si el renglon nombra una, la cantidad no puede
    -- decir tres.
    ALTER TABLE nm_incident_product
        ADD CONSTRAINT ck_nm_incident_product_pieza_es_una
        CHECK (id_inventory_asset IS NULL OR quantity = 1);
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

DO $$
BEGIN
    -- Un traslado tiene que decir a donde. Sin destino no es un traslado, es
    -- una salida sin registrar.
    ALTER TABLE nm_incident_product
        ADD CONSTRAINT ck_nm_incident_product_traslado_con_destino
        CHECK (direction <> 'traslado' OR id_location_to IS NOT NULL);
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

COMMIT;

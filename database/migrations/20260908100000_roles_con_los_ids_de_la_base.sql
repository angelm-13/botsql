-- Los cinco roles del negocio, en los identificadores que manda la base.
--
-- El cruce, medido antes de arreglarlo
-- ------------------------------------
-- El registro nombraba estos roles en los ids 14..18 mientras la base los tiene
-- en 2..6, y en los ids 2 y 3 declaraba dos roles que la base no tiene:
--
--     id   la base dice        el registro concedia
--     ---  ------------------  ----------------------
--      2   Supervisor          gerente_administrativo
--      3   Gerente             vendedor
--      4   Jefe de taller      -
--      5   Almacenista         -
--      6   Jefe de almacen     -
--
-- Contado en filas de permiso vivas: Supervisor 73 -53 en el menu- y Gerente
-- 61 -42-, los dos mas abiertos del sistema despues de Administrator; Jefe de
-- taller 6 y Almacenista 11. Es decir, los dos roles que hay que restringir
-- eran los que mas veian, y los que tienen que trabajar no podian: el
-- almacenista no tenia ni la capacidad `warehouse_voucher`, asi que no podia
-- levantar un vale.
--
-- Por que esta migracion PISA y no solo agrega
-- --------------------------------------------
-- El sembrado normal -scripts/seed_module_permissions.py- usa
-- `ON CONFLICT DO NOTHING`: solo agrega lo que falta. Aqui el problema es al
-- contrario, las filas que hay conceden lo que no toca, asi que resembrar
-- dejaria las viejas y sumaria las nuevas.
--
-- Se decidio que manda la base, y con ello reescribir las concesiones para que
-- cada rol reciba la suya. Es la excepcion a "el gestor manda" y esta acotada:
--
--   * solo los ids 2..6. Administrator y los cuatro roles del restaurante no
--     se tocan;
--   * lo que se retira se retira en LOGICO -`deletion_date`-, asi que queda
--     para consulta y la operacion se puede revisar despues;
--   * los usuarios no se mueven de rol. Nadie cambia de `id_permission`: lo que
--     cambia es lo que cada rol concede.
--
-- Como queda
-- ----------
--     2  Supervisor           29 filas
--     3  Gerente              72 filas
--     4  Jefe de taller       29 filas
--     5  Almacenista          20 filas
--     6  Jefe de almacen      42 filas
--
-- Y las capacidades del flujo de vales, que no las tenia ningun rol salvo
-- Administrator: `warehouse_voucher` y `warehouse_voucher_confirm` para los dos
-- roles de almacen, `warehouse_prevoucher` para el supervisor -que pide
-- material pero no lo surte-.
--
-- Correccion 2026-09-09, probando el flujo real de vales con un usuario
-- Almacenista de prueba: tenia `warehouse_voucher` pero no lectura de
-- `incident_type` -catalogo de "tipo de vale" que reusa la pantalla de vales
-- de Ángel-, asi que la pantalla de Vales de almacen nunca podia poblar el
-- selector de tipo y "Levantar vale" se quedaba deshabilitado para siempre.
-- Se agrega `incident_type` (solo lectura, oculto -no es un catalogo que
-- Almacenista deba administrar, solo consultar) a Almacenista y Jefe de
-- almacen, los dos roles con `warehouse_voucher`.

BEGIN;

-- id_permission NO es un numero fijo entre instalaciones -- es
-- GENERATED BY DEFAULT AS IDENTITY, y el numero real que le toca a cada rol
-- depende del orden en que corrieron las migraciones que fueron sembrando
-- `permission` en cada ambiente (mismo hallazgo que en migrate_adser.py con
-- "Almacenista": salio id=17 en adser-prod, no un numero fijo). La version
-- original de esta migracion traia 2..6 hardcodeados, que solo eran
-- correctos en la base donde se escribio -- en tyakxa-dev real son 12..16.
-- Se resuelve por nombre contra la tabla `permission` real de cada
-- instalacion, nunca por numero.
CREATE TEMP TABLE role_ids AS
SELECT id_permission, permission_description AS role_name
FROM permission
WHERE permission_description IN
    ('Supervisor', 'Gerente', 'Jefe de taller', 'Almacenista', 'Jefe de almacen')
  AND deletion_date IS NULL;

DO $$
BEGIN
    IF (SELECT count(*) FROM role_ids) <> 5 THEN
        RAISE EXCEPTION 'Se esperaban 5 roles (Supervisor, Gerente, Jefe de taller, Almacenista, Jefe de almacen) en permission y se encontraron %. Revisar antes de continuar.',
            (SELECT count(*) FROM role_ids);
    END IF;
END $$;


"""Piezas reusables para migrar un cliente nuevo desde una base legada
(MySQL/MariaDB) hacia tyakxa_tny (Postgres).

Esto es el esqueleto que se repite en cualquier migracion de este tipo:
conectar al origen, correr todo dentro de una sola transaccion con
dry-run/rollback, resolver IDs autogenerados por nombre (nunca a mano),
reajustar secuencias despues de insertar IDs manuales, y reportar conteos
reales al final.

Lo que este archivo NO resuelve, a proposito: el mapeo tabla-por-tabla, las
decisiones de que hacer con datos sucios/huecos, y las colisiones de ID
reales de cada cliente. Eso requiere criterio de negocio sobre los datos
reales de ESE cliente - ver la Skill `migrar-cliente-legado` para el
proceso de analisis completo, y `migrate_adser.py` como ejemplo de un
script real que ya usa estas piezas.

Requiere pymysql para leer el origen (`pip install pymysql`) - no es una
dependencia del proyecto, solo de las migraciones puntuales que lo usen.
"""

from __future__ import annotations

import argparse
import contextlib
from datetime import datetime

import pymysql
import pymysql.cursors
from sqlalchemy import text

from app.models.session import SessionLocal


def parser_base(descripcion: str) -> argparse.ArgumentParser:
    """ArgumentParser con las banderas comunes a cualquier migracion desde
    un origen MySQL/MariaDB hacia esta base. Cada script nuevo agrega sus
    propias banderas (ej. --imagenes-dir) antes de parsear; si el nombre de
    la base de origen tiene un default logico (ej. siempre se llama igual),
    fijarlo aparte con `parser.set_defaults(source_db='...')`.
    """
    parser = argparse.ArgumentParser(description=descripcion, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source-host', default='localhost')
    parser.add_argument('--source-port', type=int, default=13306)
    parser.add_argument('--source-user', default='root')
    parser.add_argument('--source-password', required=True)
    # Sin default aqui: si el script de un cliente siempre migra la misma
    # base, fijarlo con `parser.set_defaults(source_db='...')` despues de
    # llamar a esta funcion (set_defaults no choca con `required`, a
    # diferencia de pasarle `default=` a add_argument de otro cliente).
    parser.add_argument('--source-db')
    parser.add_argument('--dry-run', action='store_true', help='Revierte todo al final, no escribe nada permanente.')
    return parser


def conectar_origen(host: str, port: int, user: str, password: str, db: str):
    """Conexion pymysql al origen MySQL/MariaDB, con cursor tipo dict."""
    return pymysql.connect(
        host=host, port=port, user=user, password=password, database=db,
        cursorclass=pymysql.cursors.DictCursor, charset='utf8mb4',
    )


@contextlib.contextmanager
def sesion_migracion(dry_run: bool):
    """Envuelve toda la migracion en una sola transaccion de SQLAlchemy.

    dry_run=True revierte todo al final (nunca escribe nada permanente) -
    dejarlo puesto la primera vez que se corre un script nuevo, cada vez que
    cambie algo, y siempre antes de tocar una base con datos reales.
    Cualquier excepcion tambien revierte y se propaga - nunca queda una
    migracion a medias.
    """
    session = SessionLocal()
    try:
        yield session
        if dry_run:
            session.rollback()
            print("\n--dry-run: todo revertido, no se escribio nada permanente.")
        else:
            session.commit()
            print("\nMigracion confirmada.")
    except Exception:
        session.rollback()
        raise
    finally:
        session.close()


def resolver_ids_por_nombre(session, tabla: str, columna_id: str, columna_nombre: str) -> dict:
    """Resuelve IDs autogenerados por Postgres por su nombre, nunca a mano.

    Cualquier tabla con una columna GENERATED BY DEFAULT AS IDENTITY (o
    SERIAL) cuyo valor real depende del orden en que corrieron las
    migraciones del proyecto -no de un numero fijo que algun modulo de
    Python use para nombrarla en otro lado- debe resolverse asi. Caso real:
    en `permission`, "Almacenista" salio id=5 en la prueba contra datos
    reales, no el 17 que tiene `registry.py` (ese numero es solo como
    `registry.py` nombra el rol en Python, no el id real en la base).
    """
    filas = session.execute(text(f'SELECT {columna_id}, {columna_nombre} FROM "{tabla}"')).all()
    return {nombre.strip().lower(): id_ for id_, nombre in filas}


def normalizar_fecha(valor, sentinela: datetime):
    """NULL si la fecha es el sentinela de 'nunca paso' del sistema legado.

    Distintos sistemas legados (y distintas tablas del mismo sistema) suelen
    usar sentinelas distintos (ej. 1900-01-01 en una tabla, 1990-01-01 en
    otra) - pasarlo explicito en cada llamada, no asumir que es el mismo en
    todos lados.
    """
    if valor is None or valor == sentinela:
        return None
    return valor


def ajustar_secuencias(session, tablas: list[tuple[str, str]]):
    """Fijar id=X a mano en una columna SERIAL/IDENTITY no avanza su
    nextval() - sin esto, el primer INSERT normal de la app despues de la
    migracion chocaria contra un id ya usado. Mismo patron que ya usa
    `database/init.sql` para su propio bootstrap circular.

    `tablas` es una lista de (nombre_tabla, columna_id) - una por cada
    tabla donde el script de migracion inserto IDs a mano.
    """
    for tabla, columna in tablas:
        session.execute(text(
            f"SELECT setval(pg_get_serial_sequence('{tabla}', '{columna}'), "
            f"COALESCE((SELECT MAX({columna}) FROM \"{tabla}\"), 1), true)"
        ))
    print("  secuencias ajustadas al MAX(id) de cada tabla")


def reporte_conteos(session, tablas: list[tuple[str, str]]):
    """Conteos reales en destino, tabla por tabla - la unica forma confiable
    de confirmar una migracion. Nunca contar a mano ni confiar solo en lo
    que el propio script cree haber insertado.

    OJO: una tabla que ya traia filas del bootstrap circular de
    `database/init.sql` (`user`, `customer_supplier`, ...) antes de correr
    la migracion va a mostrar mas que lo recien migrado - eso es correcto,
    no es un error de conteo. Verificar el estado del destino ANTES de
    migrar (ver la Skill `migrar-cliente-legado`, paso 3) evita confundirse
    con esto despues.
    """
    print("\n--- verificacion final: conteos en destino (incluye bootstrap donde aplica) ---")
    for tabla, _columna in tablas:
        total = session.execute(text(f'SELECT COUNT(*) FROM "{tabla}"')).scalar()
        print(f"  {tabla}: {total}")

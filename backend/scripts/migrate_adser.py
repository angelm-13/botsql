def migrar_location(origen, session, equiv):
    """ubicacion -> location. Autoreferencia jerarquica; 2 filas quedan como
    raiz por razones distintas (seccion 06): id=1 se autoreferencia (choca
    con ck_location_not_self_parent), id=15 apunta a un id=14 inexistente.
    """
    cur = origen.cursor()
    cur.execute("SELECT id_ubicacion, id_tipo_ubicacion, descripcion, id_ubicacion_contenedor FROM ubicacion")
    filas = cur.fetchall()
    tipo_map = equiv['tipo_ubicacion']
    ids_existentes = {f['id_ubicacion'] for f in filas}

    mapa = {}
    max_id = max(f['id_ubicacion'] for f in filas)

    # "Sin ubicación asignada": destino de los 780 productos con
    # id_ubicacion=0 (sentinela de origen, no un id real - seccion 06). El
    # tipo no tiene ningun significado real para esta fila -se elige el de
    # menor id origen solo para que la eleccion sea reproducible, no porque
    # importe cual sea.
    id_sin_ubicacion = max_id + 1
    session.add(Location(
        id_location=id_sin_ubicacion,
        id_location_type=tipo_map[min(tipo_map)],
        location_description='Sin ubicación asignada (origen: sentinela 0)',
        id_location_reference=None,
        created_by=CREATED_BY,
    ))
    mapa[0] = id_sin_ubicacion

    # Primera pasada: crear todas las filas sin el contenedor todavia, porque
    # una fila puede referenciar a otra que aun no se inserto.
    for fila in filas:
        session.add(Location(
            id_location=fila['id_ubicacion'],
            id_location_type=tipo_map[fila['id_tipo_ubicacion']],
            location_description=fila['descripcion'],
            id_location_reference=None,
            created_by=CREATED_BY,
        ))
        mapa[fila['id_ubicacion']] = fila['id_ubicacion']
    session.flush()

    # Segunda pasada: fijar el contenedor real, dejando como raiz (NULL) la
    # autoreferencia y el huerfano de verdad.
    raices = 0
    for fila in filas:
        contenedor = fila['id_ubicacion_contenedor']
        if contenedor is None or contenedor == fila['id_ubicacion'] or contenedor not in ids_existentes:
            raices += 1
            continue
        obj = session.get(Location, fila['id_ubicacion'])
        obj.id_location_reference = contenedor

    equiv['ubicacion'] = mapa
    print(f"  location: {len(filas)} migradas + 1 'sin ubicación asignada' (id={id_sin_ubicacion}); {raices} raíces")


def migrar_material(origen, session, equiv):
    """material -> material. id_brand/id_product_family: se hereda de los
    productos que usan cada material cuando es consistente, generico si no
    (seccion 05 - hallazgo: familia es estable por material, marca no).
    """
    cur = origen.cursor()
    cur.execute("SELECT id_material, descripcion, unidad FROM material")
    filas = cur.fetchall()

    cur.execute("""
        SELECT id_material, MIN(id_familia) AS id_familia
        FROM producto WHERE id_material IS NOT NULL AND id_familia IS NOT NULL
        GROUP BY id_material HAVING COUNT(DISTINCT id_familia) = 1
    """)
    familia_por_material = {r['id_material']: r['id_familia'] for r in cur.fetchall()}

    cur.execute("""
        SELECT id_material, MIN(id_marca) AS id_marca
        FROM producto WHERE id_material IS NOT NULL AND id_marca IS NOT NULL
        GROUP BY id_material HAVING COUNT(DISTINCT id_marca) = 1
    """)
    marca_por_material = {r['id_material']: r['id_marca'] for r in cur.fetchall()}

    familia_map, marca_map, unidad_map = equiv['familia'], equiv['marca'], equiv['unidad']

    mapa = {}
    for fila in filas:
        id_product_family = familia_map.get(familia_por_material.get(fila['id_material']), familia_map['__generico__'])
        id_brand = marca_map.get(marca_por_material.get(fila['id_material']), marca_map['__generico__'])
        id_unit = unidad_map.get(fila['unidad'], unidad_map[None])
        session.add(Material(
            id_material=fila['id_material'],
            material_description=fila['descripcion'],
            id_unit=id_unit,
            id_brand=id_brand,
            id_product_family=id_product_family,
            created_by=CREATED_BY,
        ))
        mapa[fila['id_material']] = fila['id_material']

    # Generico para los 13 productos que apuntan a un id_material inexistente
    # (5 de ellos al mismo id=280 - seccion 06).
    id_generico = max(mapa.values(), default=0) + 1
    session.add(Material(
        id_material=id_generico,
        material_description='Material desconocido',
        id_unit=unidad_map[None],
        id_brand=marca_map['__generico__'],
        id_product_family=familia_map['__generico__'],
        created_by=CREATED_BY,
    ))
    mapa['__generico__'] = id_generico

    session.flush()
    equiv['material'] = mapa
    print(f"  material: {len(filas)} migrados + 1 generico (id={id_generico})")


def migrar_user(origen, session, equiv):
    """usuario + empleado -> user, fusionados donde la liga es real.

    Solo 2 de 40 empleado.id_usuario no nulos corresponden a una cuenta real
    (fernanda, yesgo); taroj no tiene fila en empleado. Los otros 39 se crean
    como user nuevo, is_employee=True, sin acceso (seccion 06).

    id_permission de los 39 sin cuenta: se asume Almacenista (mismo criterio
    operativo que fernanda/yesgo) ya que nunca inician sesion y no se discutio
    un rol especifico para ellos - confirmar si Alan quiere otro.
    """
    cur = origen.cursor()
    cur.execute("SELECT id_usuario, fecha_creacion, fecha_ultima_actualizacion, fecha_baja, "
                "tipo_usuario, username, contrasena FROM usuario")
    usuarios = cur.fetchall()

    cur.execute("SELECT id_empleado, nombres, apellido_paterno, apellido_materno, telefono_principal, "
                "correo, puesto, nss, curp, rfc, fecha_ingreso, fecha_nacimiento, id_usuario, tratamiento "
                "FROM empleado")
    empleados = cur.fetchall()

    # OJO: 38 de los 40 empleado.id_usuario no nulos son huerfanos (no
    # corresponden a ninguna fila real de usuario - seccion 06). Filtrar por
    # el conjunto de ids reales ANTES de armar el diccionario evita que un
    # huerfano choque por casualidad con 1/2/34 y desplace a fernanda o yesgo
    # (asi se produjo un duplicado la primera vez que corrio este script).
    ids_usuario_reales = {u['id_usuario'] for u in usuarios}
    empleado_por_id_usuario = {
        e['id_usuario']: e for e in empleados if e['id_usuario'] in ids_usuario_reales
    }
    assert len(empleado_por_id_usuario) == 2, (
        f"se esperaban exactamente 2 empleados con liga real a usuario "
        f"(fernanda, yesgo); salieron {len(empleado_por_id_usuario)} - revisar antes de continuar"
    )

    permission_ids = resolver_ids_por_nombre(session, 'permission', 'id_permission', 'permission_description')
    id_almacenista = permission_ids['almacenista']

    mapa_usuario = {}   # id_usuario (origen) -> id_user (destino) - los 3 reales
    mapa_empleado = {}  # id_empleado (origen) -> id_user (destino) - los 41 completos
    id_taroj_nuevo = None

    # Paso 1: los 3 usuarios reales de sistema.
    for u in usuarios:
        # tipo_usuario (origen): solo 'admin' y 'almacen' existen, verificado
        # exhaustivamente contra los datos reales (seccion 06). Un tercer
        # valor detiene el script en vez de tratarse como 'almacen' en
        # silencio - el mismo criterio que ya usa este archivo en la
        # asercion de arriba.
        if u['tipo_usuario'] == 'admin':
            id_permission, user_type = permission_ids['administrator'], 'admin'
        elif u['tipo_usuario'] == 'almacen':
            id_permission, user_type = id_almacenista, 'employee'
        else:
            raise ValueError(f"tipo_usuario inesperado: {u['tipo_usuario']!r} (usuario id={u['id_usuario']})")
        empleado = empleado_por_id_usuario.get(u['id_usuario'])
        es_taroj = u['username'] == 'taroj'
        id_nuevo = ID_NUEVO_TAROJ if es_taroj else u['id_usuario']

        obj = User(
            id_user=id_nuevo,
            username=u['username'],
            password=u['contrasena'],
            full_name=(nombre_completo(empleado) if empleado else u['username']) or u['username'],
            user_type=user_type,
            id_permission=id_permission,
            id_proyect=BOOTSTRAP_ID_PROYECT,
            id_status=BOOTSTRAP_ID_STATUS,
            supervisor=0,  # placeholder; se corrige al final de esta funcion
            is_employee=empleado is not None,
            puesto=empleado['puesto'] if empleado else None,
            national_id=empleado['curp'] if empleado else None,
            ssn=empleado['nss'] if empleado else None,
            tax_id=empleado['rfc'] if empleado else None,
            title=empleado['tratamiento'] if empleado else None,
            principal_phone=empleado['telefono_principal'] if empleado else None,
            email=empleado['correo'] if empleado else None,
            hire_date=empleado['fecha_ingreso'] if empleado else None,
            date_born=empleado['fecha_nacimiento'] if empleado else None,
            creation_date=u['fecha_creacion'],
            last_update_date=u['fecha_ultima_actualizacion'],
            deletion_date=normalizar_fecha(u['fecha_baja'], datetime(1900, 1, 1)),
            created_by=CREATED_BY,
        )
        session.add(obj)
        mapa_usuario[u['id_usuario']] = id_nuevo
        if empleado:
            mapa_empleado[empleado['id_empleado']] = id_nuevo
        if es_taroj:
            id_taroj_nuevo = id_nuevo
    session.flush()

    # Paso 2: los empleados sin cuenta real (38 huerfanos + 1 nulo = 39, ver
    # seccion 06) -> user nuevo, sin acceso al sistema.
    siguiente_id = max(mapa_usuario.values()) + 1
    for empleado in empleados:
        if empleado['id_empleado'] in mapa_empleado:
            continue
        obj = User(
            id_user=siguiente_id,
            username=None,
            password=None,
            full_name=nombre_completo(empleado) or f"Empleado {empleado['id_empleado']}",
            user_type='employee',
            id_permission=id_almacenista,
            id_proyect=BOOTSTRAP_ID_PROYECT,
            id_status=BOOTSTRAP_ID_STATUS,
            supervisor=0,  # se corrige abajo
            is_employee=True,
            puesto=empleado['puesto'],
            national_id=empleado['curp'],
            ssn=empleado['nss'],
            tax_id=empleado['rfc'],
            title=empleado['tratamiento'],
            principal_phone=empleado['telefono_principal'],
            email=empleado['correo'],
            hire_date=empleado['fecha_ingreso'],
            date_born=empleado['fecha_nacimiento'],
            created_by=CREATED_BY,
        )
        session.add(obj)
        mapa_empleado[empleado['id_empleado']] = siguiente_id
        siguiente_id += 1
    session.flush()

    # Paso 3: supervisor = taroj para las 43 personas migradas (seccion 06:
    # empleado.supervisor viene vacio al 100%, sin jerarquia real que heredar).
    for id_destino in set(mapa_usuario.values()) | set(mapa_empleado.values()):
        session.get(User, id_destino).supervisor = id_taroj_nuevo

    equiv['usuario'] = mapa_usuario
    equiv['empleado'] = mapa_empleado
    equiv['taroj'] = id_taroj_nuevo
    empleados_sin_cuenta = len(empleados) - len(empleado_por_id_usuario)
    print(f"  user: {len(mapa_usuario)} desde usuario (taroj -> id={id_taroj_nuevo}) "
          f"+ {empleados_sin_cuenta} desde empleado sin cuenta")


def migrar_customer_supplier(origen, session, equiv):
    """cliente_proveedor -> customer_supplier. id_usuario=9 no existe en
    origen (huerfano en las 2 filas) -> taroj como dueña real (seccion 06).
    """
    cur = origen.cursor()
    cur.execute("SELECT id_cliente_proveedor, codigo_postal, razon_social, tratamiento, nombre_contacto, "
                "telefono, sitio_web, calle, numero_ext, numero_int, colonia, ciudad, estado, regimen, "
                "fecha_ultima_constancia, rfc, tipo, id_usuario FROM cliente_proveedor")
    filas = cur.fetchall()
    usuario_map, id_taroj_nuevo = equiv['usuario'], equiv['taroj']

    mapa = {}
    for fila in filas:
        es_adser_sa = fila['id_cliente_proveedor'] == 1
        id_nuevo = ID_NUEVO_ADSER_SA_DE_CV if es_adser_sa else fila['id_cliente_proveedor']
        session.add(CustomerSupplier(
            id_customer_supplier=id_nuevo,
            postal_code=fila['codigo_postal'],
            name=fila['razon_social'],
            title=fila['tratamiento'],
            contact_name=fila['nombre_contacto'],
            phone=fila['telefono'],
            web_site=fila['sitio_web'],
            street=fila['calle'],
            number_ext=fila['numero_ext'],
            number_int=fila['numero_int'],
            neighborhood=fila['colonia'],
            city=fila['ciudad'],
            geographic_state=fila['estado'],
            fiscal_type=fila['regimen'],
            last_fiscal_certification_date=fila['fecha_ultima_constancia'],
            tax_id=fila['rfc'],
            type='supplier' if fila['tipo'] == 'proveedor' else 'client',
            id_user=usuario_map.get(fila['id_usuario'], id_taroj_nuevo),
            created_by=CREATED_BY,
        ))
        mapa[fila['id_cliente_proveedor']] = id_nuevo

    session.flush()
    equiv['cliente_proveedor'] = mapa
    print(f"  customer_supplier: {len(filas)} migrados (Adser SA de CV -> id={ID_NUEVO_ADSER_SA_DE_CV})")


def migrar_invoice(origen, session, equiv):
    """factura -> invoice, tal cual. Los 4 campos que el origen nunca tuvo
    (apply_tax, tax_certification_supplier, id_issuer_customer_supplier,
    id_status) se completan con la misma regla que usaria la app hoy, no con
    valores inventados (seccion 05: "Las 2 facturas placeholder...").
    """
    cur = origen.cursor()
    cur.execute("SELECT id_factura, serie, folio, fecha_emision, fecha_vencimiento, condiciones_pago, "
                "forma_pago, subtotal, descuento, impuesto, total, lugar_expedicion, estado, metodo_pago, "
                "tipo_de_comprobante, notas, nombre_emisor, rfc_receptor, nombre_receptor, uso_cfdi, "
                "regimen_fiscal_receptor, domicilio_fiscal_receptor, folio_fiscal, serie_csd, exportacion, "
                "moneda, tipo_cambio, no_certificado_sat, fecha_de_certificacion, sello_cfdi, sello_sat, "
                "sello_certificacion_sat, no_certificado, id_cliente_proveedor FROM factura ORDER BY id_factura")
    filas = cur.fetchall()
    cliente_map = equiv['cliente_proveedor']

    mapa = {}
    primera_id = None
    for fila in filas:
        id_customer_supplier = cliente_map[fila['id_cliente_proveedor']]
        session.add(Invoice(
            id_invoice=fila['id_factura'],
            date_emision=fila['fecha_emision'],
            date_expiration=fila['fecha_vencimiento'],
            subtotal=fila['subtotal'],
            descuento=fila['descuento'],
            tax=fila['impuesto'],
            total=fila['total'],
            invoice_status=fila['estado'],
            payment_method=fila['metodo_pago'],
            metodo_pago=fila['metodo_pago'],
            forma_pago=fila['forma_pago'],
            note=fila['notas'],
            id_customer_supplier=id_customer_supplier,
            # Autofactura de apertura: emisor = receptor (seccion 05).
            id_issuer_customer_supplier=id_customer_supplier,
            tax_certification_supplier=id_customer_supplier,
            apply_tax=(fila['impuesto'] or 0) > 0,
            id_status=BOOTSTRAP_ID_STATUS,
            # id_proyect=None se dejo asi originalmente -- descubierto despues
            # (2026-09-09, fix_adser_invoice_id_proyect.py) que NULL rompe
            # inventory_trace_service: ningun usuario no-admin puede ver un
            # producto cuya factura no coincida con su propio id_proyect.
            id_proyect=BOOTSTRAP_ID_PROYECT,
            lugar_expedicion=fila['lugar_expedicion'],
            tipo_de_comprobante=fila['tipo_de_comprobante'],
            rfc_receptor=fila['rfc_receptor'],
            nombre_receptor=fila['nombre_receptor'],
            nombre_emisor=fila['nombre_emisor'],
            uso_cfdi=fila['uso_cfdi'],
            regimen_fiscal_receptor=fila['regimen_fiscal_receptor'],
            domicilio_fiscal_receptor=fila['domicilio_fiscal_receptor'],
            folio_fiscal=fila['folio_fiscal'],
            serie_csd=fila['serie_csd'],
            exportacion=fila['exportacion'],
            currency=fila['moneda'],
            type_exchange_rate=fila['tipo_cambio'],
            no_certificado_sat=fila['no_certificado_sat'],
            certification_date=fila['fecha_de_certificacion'],
            cfdi_code=fila['sello_cfdi'],
            sat_code=fila['sello_sat'],
            sat_certification_code=fila['sello_certificacion_sat'],
            no_certificado=fila['no_certificado'],
            folio=fila['folio'],
            condiciones_pago=fila['condiciones_pago'],
            manual_capture=False,
            created_by=CREATED_BY,
        ))
        mapa[fila['id_factura']] = fila['id_factura']
        if primera_id is None:
            primera_id = fila['id_factura']

    # id_factura=0 (sentinela "sin factura", 1,457 productos - seccion 06) ->
    # la primera factura migrada (folio "AA").
    mapa[0] = primera_id

    session.flush()
    equiv['factura'] = mapa
    print(f"  invoice: {len(filas)} migradas; id_factura=0 -> factura {primera_id} (folio AA)")


def migrar_product(origen, session, equiv):
    """producto -> product. La tabla mas grande y con mas huecos resueltos
    (seccion 05-06): is_directly_related_to_product_service=False,
    stock_purpose='uso_interno' para todo, id_ubicacion llega como texto.
    """
    cur = origen.cursor()
    cur.execute("SELECT id_producto, id_factura, id_material, id_ubicacion, id_marca, id_familia, "
                "fecha_creacion, fecha_ultima_actualizacion, fecha_baja, precio_bruto, descripcion, "
                "estado, path_imagen, codigo, nota, color, cantidad FROM producto")
    filas = cur.fetchall()

    factura_map, material_map, ubicacion_map = equiv['factura'], equiv['material'], equiv['ubicacion']

    mapa = {}
    for fila in filas:
        session.add(Product(
            id_product=fila['id_producto'],
            id_invoice=factura_map[fila['id_factura']],
            id_location=ubicacion_map[int(fila['id_ubicacion'])],
            id_material=material_map.get(fila['id_material'], material_map['__generico__']),
            gross_price=fila['precio_bruto'],
            color=fila['color'],
            is_directly_related_to_product_service=False,
            product_status=fila['estado'],
            path_imagen=fila['path_imagen'],
            product_code=fila['codigo'],
            note=fila['nota'],
            descripcion=fila['descripcion'],
            cantidad=fila['cantidad'],
            tracking_mode='fungible',
            stock_purpose='uso_interno',
            id_marca=fila['id_marca'],
            id_familia=fila['id_familia'],
            creation_date=fila['fecha_creacion'],
            last_update_date=fila['fecha_ultima_actualizacion'],
            deletion_date=normalizar_fecha(fila['fecha_baja'], datetime(1990, 1, 1)),
            created_by=CREATED_BY,
        ))
        mapa[fila['id_producto']] = fila['id_producto']

    session.flush()
    equiv['producto'] = mapa
    print(f"  product: {len(filas)} migrados")


def migrar_incident(origen, session, equiv):
    """incidente -> incident. id_empleado se resuelve contra el mapa
    completo de 41 empleados (fusionados o creados sin acceso) - sin eso,
    138 de 139 incidentes se quedarian sin id_user valido (seccion 06).
    """
    cur = origen.cursor()
    cur.execute("SELECT id_incidente, fecha_incidente, id_tipo_incidente, nota, id_empleado, "
                "estado, fecha_cierre FROM incidente")
    filas = cur.fetchall()

    tipo_map, empleado_map = equiv['tipo_incidente'], equiv['empleado']

    mapa = {}
    for fila in filas:
        session.add(Incident(
            id_incident=fila['id_incidente'],
            incident_date=fila['fecha_incidente'],
            id_incident_type=tipo_map[fila['id_tipo_incidente']],
            note=fila['nota'],
            id_user=empleado_map[fila['id_empleado']],
            incident_status=fila['estado'],
            close_date=fila['fecha_cierre'],
            id_lider=None,  # siempre vacio en origen, verificado (seccion 06)
            created_by=CREATED_BY,
        ))
        mapa[fila['id_incidente']] = fila['id_incidente']

    session.flush()
    equiv['incidente'] = mapa
    print(f"  incident: {len(filas)} migrados")


def migrar_nm_incident_product(origen, session, equiv):
    """nm_incidente_producto -> nm_incident_product. 19 filas se excluyen
    porque el producto al que apuntan no existe en origen (seccion 06).
    """
    cur = origen.cursor()
    cur.execute("SELECT id_nm_incidente_producto, id_incidente, id_producto, nota, cantidad, "
                "fecha_cierre FROM nm_incidente_producto")
    filas = cur.fetchall()

    incidente_map, producto_map = equiv['incidente'], equiv['producto']

    migrados = excluidos = 0
    for fila in filas:
        if fila['id_producto'] not in producto_map:
            excluidos += 1
            continue
        session.add(NmIncidentProduct(
            id_nm_incident_product=fila['id_nm_incidente_producto'],
            id_incident=incidente_map[fila['id_incidente']],
            id_product=producto_map[fila['id_producto']],
            note=fila['nota'],
            quantity=fila['cantidad'],
            close_date=fila['fecha_cierre'],
            created_by=CREATED_BY,
        ))
        migrados += 1

    session.flush()
    print(f"  nm_incident_product: {migrados} migrados, {excluidos} excluidos (producto inexistente)")


